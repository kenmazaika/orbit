// Inlines dist/ into a single JS module so the worker needs no assets binding.
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;
const OUT = new URL('../worker/assets.generated.js', import.meta.url).pathname;

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2', '.woff': 'font/woff', '.png': 'image/png',
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp',
  '.ico': 'image/x-icon', '.json': 'application/json', '.txt': 'text/plain; charset=utf-8',
};

const out = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = '/' + relative(DIST, p).split('\\').join('/');
    const type = TYPES[extname(p).toLowerCase()] || 'application/octet-stream';
    out[rel] = [type, readFileSync(p).toString('base64')];
  }
}
walk(DIST);

const body = `// generated by scripts/bundle-assets.mjs — do not edit\nexport default ${JSON.stringify(out)};\n`;
writeFileSync(OUT, body);
const kb = (Buffer.byteLength(body) / 1024).toFixed(1);
console.log(`bundled ${Object.keys(out).length} assets into worker/assets.generated.js (${kb} KB)`);
